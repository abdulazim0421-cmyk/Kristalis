    const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
    const translit = (w) => [...w.toLowerCase()].map(c => (c in TR ? TR[c] : c)).join("");

    function convert(name, lang) {
        const en = lang === "en";
        const dict = en ? EN : KY;
        let s = name.replace(/([cC])(?=[А-Яа-яЁё])/g, m => (m === "c" ? "с" : "С"));
        s = s.replace(/в ассортименте/gi, en ? "assorted" : "ассортиментте");
        if (en) {
            s = s.replace(/(\d)\s*л\.?(?![а-яё])/gi, "$1 l");
            s = s.replace(/(\d)\s*гр\.?(?![а-яё])/gi, "$1 g");
            s = s.replace(/(\d)\s*шт\.?(?![а-яё])/gi, "$1 pcs");
            s = s.replace(/(\d),(\d)/g, "$1.$2");
        }
        s = s.replace(/([А-Яа-яЁё]+)(\.(?![A-Za-zА-Яа-яЁё]))?/g, (m, w, dot) => {
            const key = w.toLowerCase();
            const up = w.charAt(0) !== key.charAt(0);
            const hit = dict[key];
            if (hit !== undefined)
                return up ? cap(hit) : hit;
            if (en) {
                const r = translit(w);
                return (up ? cap(r) : r) + (dot || "");
            }
            return m;
        });
        return s.replace(/\s{2,}/g, " ").trim();
    }

